#!/usr/bin/env python3
"""
BibTeX Collector — aggregate all bibentry.bib files into a single references.bib.

Recursively walks knowledge/<category>/ for all bibentry.bib files and
merges them into knowledge/<category>/references.bib.

Usage:
    python collect-bib.py knowledge/<category>/
    python collect-bib.py knowledge/<category>/ --output references.bib

Dependencies: bibtexparser (pip install bibtexparser --pre)
"""

import sys
import os
from pathlib import Path


def find_bib_files(root: Path) -> list[Path]:
    """Find all bibentry.bib files under root."""
    return sorted(root.rglob("bibentry.bib"))


def collect_entries(bib_files: list[Path]) -> list[str]:
    """Read all bibentry.bib files and return list of raw BibTeX entry strings."""
    entries = []
    seen_keys = set()
    for f in bib_files:
        content = f.read_text(encoding="utf-8").strip()
        if not content:
            print(f"  [WARN] Empty file: {f}")
            continue
        # Extract citation key for dedup check
        for line in content.split("\n"):
            line = line.strip()
            if line.startswith("@") and "{" in line:
                key = line.split("{", 1)[1].rstrip(",").rstrip(")")
                if key in seen_keys:
                    print(f"  [SKIP] Duplicate key '{key}' in {f}")
                else:
                    seen_keys.add(key)
                    entries.append(content)
                break
        else:
            entries.append(content)
    return entries


def write_references(output_path: Path, entries: list[str]) -> None:
    """Write all entries to references.bib with header comment."""
    header = (
        f"% Aggregated BibTeX references\n"
        f"% Generated by scripts/collect-bib.py\n"
        f"% Total entries: {len(entries)}\n"
        f"% Import into Zotero/Mendeley or use with \\bibliography{{references}}\n\n"
    )
    output_path.write_text(header + "\n\n".join(entries) + "\n", encoding="utf-8")


def main():
    if len(sys.argv) < 2:
        print("Usage: python collect-bib.py knowledge/<category>/ [--output <name>]")
        sys.exit(1)

    root = Path(sys.argv[1])
    if not root.is_dir():
        print(f"Error: '{root}' is not a directory")
        sys.exit(1)

    output_name = "references.bib"
    if "--output" in sys.argv:
        idx = sys.argv.index("--output")
        output_name = sys.argv[idx + 1]

    output_path = root / output_name
    bib_files = find_bib_files(root)

    if not bib_files:
        print(f"No bibentry.bib files found under {root}")
        sys.exit(0)

    print(f"Found {len(bib_files)} bibentry.bib files:")
    for f in bib_files:
        print(f"  {f.relative_to(root)}")

    entries = collect_entries(bib_files)
    write_references(output_path, entries)

    print(f"\nDone: {len(entries)} entries written to {output_path}")


if __name__ == "__main__":
    main()
